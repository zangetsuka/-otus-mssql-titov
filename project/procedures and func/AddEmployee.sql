ALTER PROCEDURE AddEmployee
    @ФИО NVARCHAR(255),               -- Полное имя сотрудника (ФИО)
    @должность NVARCHAR(255),         -- Должность сотрудника
    @отдел_название NVARCHAR(255),    -- Название отдела
    @организация_название NVARCHAR(255) -- Название организации
AS
BEGIN
    -- Отключаем дополнительные сообщения
    SET NOCOUNT ON;

    DECLARE @отдел_id INT;            -- Переменная для ID отдела
    DECLARE @организация_id INT;      -- Переменная для ID организации

    -- Получаем ID организации по названию
    SELECT @организация_id = id
    FROM Организация
    WHERE название = @организация_название;

    -- Проверяем, найдена ли организация
    IF @организация_id IS NULL
    BEGIN
        PRINT 'Организация не найдена!';
        RETURN;
    END;

    -- Получаем ID отдела
    SELECT @отдел_id = id
    FROM Отдел
    WHERE название_id = (SELECT id FROM Названия_Отделов WHERE название = @отдел_название)
      AND организация_id = @организация_id;

    -- Проверяем, найден ли отдел
    IF @отдел_id IS NOT NULL
    BEGIN
        -- Добавляем сотрудника
        INSERT INTO Сотрудник (ФИО, должность, отдел_id)
        VALUES (@ФИО, @должность, @отдел_id);

        PRINT 'Сотрудник добавлен успешно!';
    END
    ELSE
    BEGIN
        PRINT 'Отдел не найден!';
    END;
END;
GO
